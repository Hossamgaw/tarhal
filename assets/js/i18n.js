/**
 * Get translated text by key path
 * Example: t('home.hero') → returns "كل رحلات العالم في مكان واحد"
 */
function t(path) {
  const locale = typeof getLocale === 'function' ? getLocale() : 'ar';
  const parts = path.split('.');
  let result = TRANSLATIONS[locale];

  for (const part of parts) {
    if (result && typeof result === 'object' && part in result) {
      result = result[part];
    } else {
      return path; // fallback: return the key if not found
    }
  }

  return typeof result === 'string' ? result : path;
}

/**
 * Translate with variable replacement
 * Example: tVar('trip.dayNum', { n: 3 }) → "اليوم 3"
 */
function tVar(path, vars = {}) {
  let text = t(path);
  for (const [key, value] of Object.entries(vars)) {
    text = text.replace(new RegExp(`\\{${key}\\}`, 'g'), value);
  }
  return text;
}